    /**
     * @param  list<string>  $terms
     * @return list<LexiconEntry>
     */
    private static function pack(
        string $severity,
        string $category,
        string $signal,
        array $terms,
        bool $boundedShort = false,
        bool $forceBounded = false,
    ): array {
        $out = [];
        foreach ($terms as $term) {
            $term = trim($term);
            if ($term === '') {
                continue;
            }
            $bounded = $forceBounded;
            if ($boundedShort && ! $bounded) {
                $compactLen = mb_strlen(preg_replace('/\s+/u', '', $term) ?? $term);
                $bounded = $compactLen <= 3;
            }
            $out[] = [
                'term' => $term,
                'severity' => $severity,
                'category' => $category,
                'signal' => $signal,
                'bounded' => $bounded,
            ];
        }

        return $out;
    }
